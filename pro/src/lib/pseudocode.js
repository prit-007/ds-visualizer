export const SORTING_PSEUDOCODE = {
  bubble: [
    'procedure bubbleSort(array)',
    '  n ← length(array)',
    '  for pass ← 1 to n - 1 do',
    '    for i ← 0 to n - pass - 1 do',
    '      if array[i] > array[i + 1] then swap(array[i], array[i + 1])',
    '    array[n - pass] is now sorted',
    '  if no swaps happened then return early',
    '  return sorted array',
  ],
  selection: [
    'procedure selectionSort(array)',
    '  n ← length(array)',
    '  for pass ← 1 to n - 1 do',
    '    min ← pass - 1',
    '    for j ← pass to n - 1 do',
    '      if array[j] < array[min] then min ← j',
    '    swap(array[pass - 1], array[min])',
    '  return sorted array',
  ],
  insertion: [
    'procedure insertionSort(array)',
    '  n ← length(array)',
    '  for i ← 1 to n - 1 do',
    '    key ← array[i]',
    '    j ← i - 1',
    '    while j ≥ 0 and array[j] > key do',
    '      array[j + 1] ← array[j]',
    '      j ← j - 1',
    '    array[j + 1] ← key',
    '  return sorted array',
  ],
};

export const TREE_ALGO_PSEUDOCODE = {
  bfs: [
    'procedure bfs(root)',
    '  queue ← [root]',
    '  while queue ≠ ∅ do',
    '    u ← dequeue(queue)',
    '    visit u',
    '    if u.left ≠ null then enqueue(queue, u.left)',
    '    if u.right ≠ null then enqueue(queue, u.right)',
    '  return visit order',
    'end procedure',
  ],
  dfs: [
    'procedure dfs(root)',
    '  stack ← [root]',
    '  while stack ≠ ∅ do',
    '    u ← pop(stack)',
    '    visit u',
    '    if u.right ≠ null then push(stack, u.right)',
    '    if u.left ≠ null then push(stack, u.left)',
    '  return visit order',
    'end procedure',
  ],
  validate: [
    'procedure validateBST(node, lo, hi)',
    '  if node = null then return true',
    '  if node.value ≤ lo or node.value ≥ hi then return false',
    '  validateBST(node.left, lo, node.value)',
    '  validateBST(node.right, node.value, hi)',
    '  return true',
    'end procedure',
  ],
  mirror: [
    'procedure mirror(node)',
    '  if node = null then return',
    '  if node.left = null and node.right = null then return',
    '  swap(node.left, node.right)',
    '  mirror(node.left)',
    '  mirror(node.right)',
    'end procedure',
  ],
  lca: [
    'procedure lca(node, a, b)',
    '  if not contains(node, a) then return "a missing"',
    '  if not contains(node, b) then return "b missing"',
    '  if a < node.value and b < node.value then return lca(node.left, a, b)',
    '  if a > node.value and b > node.value then return lca(node.right, a, b)',
    '  return node',
    'end procedure',
  ],
};

SORTING_PSEUDOCODE.merge = [
  'procedure mergeSort(array)',
  '  if length(array) ≤ 1 then return array',
  '  mid ← length(array) ÷ 2',
  '  left ← mergeSort(array[0..mid-1])',
  '  right ← mergeSort(array[mid..end])',
  '  for each comparison during merge(left, right):',
  '    append the smaller head to the result',
  '  append any remaining elements',
  '  return merged array',
  'end procedure',
];

SORTING_PSEUDOCODE.quick = [
  'procedure quickSort(array, lo, hi)',
  '  if lo ≥ hi then return array',
  '  pivot ← array[hi]',
  '  partition: move elements ≤ pivot left of the pivot',
  '  p ← final pivot position',
  '  recurse on [lo..p-1] and [p+1..hi]',
  '  return array',
  'end procedure',
];

SORTING_PSEUDOCODE.heap = [
  'procedure heapSort(array)',
  '  n ← length(array)',
  '  build max-heap',
  '  sift-down: swap parent with larger child until heap property holds',
  '  for end ← n-1 downto 1 do',
  '    swap(array[0], array[end])  ▸ extract max',
  '    sift-down(0, end-1)         ▸ restore heap',
  '  return array',
  'end procedure',
];

