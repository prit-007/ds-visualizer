export const HASH_TABLE_PSEUDOCODE = {
  insert: [
    'procedure hashInsert(table, key)',
    '  h ← hash(key)',
    '  chain ← bucket[h]',
    '  if chain is empty then',
    '    bucket[h] ← [key]',
    '  else',
    '    append key to chain',
    '  size ← size + 1',
    'end procedure',
  ],
  search: [
    'procedure hashSearch(table, key)',
    '  h ← hash(key)',
    '  chain ← bucket[h]',
    '  if chain is empty then',
    '    return not found',
    '  for i ← 0 to length(chain) - 1 do',
    '    if chain[i] = key then',
    '      return i',
    '  return not found',
    'end procedure',
  ],
  delete: [
    'procedure hashDelete(table, key)',
    '  h ← hash(key)',
    '  chain ← bucket[h]',
    '  if chain is empty then',
    '    return not found',
    '  for i ← 0 to length(chain) - 1 do',
    '    if chain[i] = key then',
    '      for j ← i+1 to length(chain)-1 do',
    '        chain[j - 1] ← chain[j]',
    '      size ← size - 1',
    '      return i',
    '  return not found',
    'end procedure',
  ],
};

export const GRAPH_PSEUDOCODE = {
  addNode: [
    'procedure graphAddNode(graph, value)',
    '  graph.nodes ← graph.nodes ∪ {value}',
    '  n ← n + 1',
    'end procedure',
  ],
  addEdge: [
    'procedure graphAddEdge(graph, u, v)',
    '  assert u ∈ nodes ∧ v ∈ nodes',
    '  assert (u, v) ∉ edges ∧ u ≠ v',
    '  edges ← edges ∪ {(u, v)}',
    '  e ← e + 1',
    'end procedure',
  ],
  bfs: [
    'procedure graphBFS(graph, start)',
    '  queue ← [start]',
    '  visited ← ∅',
    '  while queue ≠ ∅ do',
    '    u ← dequeue(queue)',
    '    visit u',
    '    for each neighbor v of u do',
    '      if v ∉ visited then',
    '        visited ← visited ∪ {v}',
    '        enqueue(queue, v)',
    '  return visit order',
    'end procedure',
  ],
  dfs: [
    'procedure graphDFS(graph, start)',
    '  visited ← ∅',
    '  order ← []',
    '  procedure visit(u)',
    '    visited ← visited ∪ {u}',
    '    order ← order ∪ [u]',
    '    for each neighbor v of u do',
    '      if v ∈ visited then skip v',
    '      else visit(v)',
    '  visit(start)',
    '  return order',
    'end procedure',
  ],
};

